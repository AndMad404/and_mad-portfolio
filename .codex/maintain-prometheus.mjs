import fs from 'node:fs';
import path from 'node:path';
import { pathToFileURL } from 'node:url';
const root = path.resolve(import.meta.dirname, '..');
if (path.resolve(process.cwd()) !== root) throw new Error('Run from the portfolio root');
const base = 'C:/Users/and_m/Documents/Profesional/DesarrolloAsistidoIA';
const load = (relative) => import(pathToFileURL(path.join(base, relative)).href);
const profile = JSON.parse(fs.readFileSync(path.join(base,'.codex/dependency-librarian/profile.json'),'utf8'));
const { findProject, filesystemFiles } = await load('.codex/dependency-librarian/reader.mjs');
const project = findProject(profile,root);
if (!project || path.resolve(project.indexPath) !== path.join(root,'dependency-index.json')) throw new Error('Project registration mismatch');
const index = JSON.parse(fs.readFileSync(project.indexPath,'utf8').replace(/^\uFEFF/,''));
const { validateIndex } = await load('.codex/dependency-editor/validate.mjs');
validateIndex(index);
const files = filesystemFiles(root,project.fileDiscovery,index.ignoreGlobs);
const { technicalGraph, technicalRelations, graphSnapshot } = await load('core/resolver-engine.mjs');
const graph = await technicalGraph(root,files,index);
const next = {...index,schemaVersion:2,graphSnapshot:graphSnapshot(technicalRelations(root,files,graph))};
delete next.generatedRelations;
validateIndex(next);
fs.writeFileSync(project.indexPath,JSON.stringify(next,null,2)+'\n');
const { generateInventory } = await load('.codex/indexation-librarian/inventory-generator.mjs');
const contexts = JSON.parse(fs.readFileSync(path.join(base,'.codex/context-librarian/profile.json'),'utf8'));
const context = contexts.projects.find(p=>p.name===project.name);
if(!context) throw new Error('Missing context registration');
const report = generateInventory(context);
console.log(JSON.stringify({project:project.name,sourceFiles:files.length,relations:next.graphSnapshot.relationCount,inventory:report},null,2));
